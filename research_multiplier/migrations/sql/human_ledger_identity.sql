-- The same identity resolver applies to existing ledgers and new hook sites.
-- Keep copies of older decisions and program decisions with their original provenance.
CREATE OR REPLACE FUNCTION rm.attribute_local_user() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, rm, pg_temp AS $$
DECLARE resolved uuid;
BEGIN
    IF TG_TABLE_NAME = 'decisions' THEN
        IF NEW.decided_by <> 'human' OR NEW.authenticated_role IS DISTINCT FROM session_user THEN
            RETURN NEW;
        END IF;
    END IF;
    IF NOT is_local_human_session() THEN
        RETURN NEW;
    END IF;
    SELECT u.id INTO resolved FROM current_local_user() u;
    IF resolved IS NULL THEN
        RAISE EXCEPTION 'resolve the authenticated local researcher before writing' USING ERRCODE = '42501';
    END IF;

    IF TG_ARGV[0] = 'cancellation' THEN
        -- Keep the plan creator's ID, including old plans created before attribution.
        IF NEW.cancelled_user_id IS NOT NULL AND NEW.cancelled_user_id IS DISTINCT FROM resolved THEN
            RAISE EXCEPTION 'resolve the authenticated local researcher before writing' USING ERRCODE = '42501';
        END IF;
        NEW.cancelled_user_id := resolved;
    ELSE
        IF NEW.user_id IS NOT NULL AND NEW.user_id IS DISTINCT FROM resolved THEN
            RAISE EXCEPTION 'resolve the authenticated local researcher before writing' USING ERRCODE = '42501';
        END IF;
        NEW.user_id := resolved;
    END IF;
    RETURN NEW;
END $$;

-- Attribute records at their primary write. Derived children and aggregate
-- rows inherit the provenance of that record and need no extra attribution.
DO $$
DECLARE relation text;
BEGIN
    FOREACH relation IN ARRAY ARRAY[
        'checker_hold_releases', 'checker_monitor_policies', 'evaluation_approvals', 'formalization_packets',
        'human_time_entries', 'incident_regressions', 'lean_eval_corpora', 'lean_route_events',
        'lean_search_budget_changes', 'lean_statements', 'literature_search_links', 'literature_searches',
        'literature_source_confirmations', 'literature_sources', 'literature_vectors', 'novelty_reviews',
        'packet_library_items', 'project_model_dispatches', 'project_model_limits', 'project_model_tariffs',
        'research_condition_rechecks', 'research_condition_requests', 'research_conjectures',
        'research_discussion_archives', 'research_goals', 'research_intake_drafts', 'research_plans',
        'research_progress_policies', 'shadow_review_times', 'shadow_route_events', 'verifier_reports'
    ]
    LOOP
        EXECUTE format('ALTER TABLE rm.%I ADD COLUMN user_id uuid REFERENCES rm.local_users(id)', relation);
        EXECUTE format('CREATE TRIGGER attribute_local_user BEFORE INSERT ON rm.%I '
                       'FOR EACH ROW EXECUTE FUNCTION rm.attribute_local_user()', relation);
    END LOOP;
END $$;

-- A clarification question can be generated by a model. Record the person
-- who actually answers or dismisses it, and leave that decision intact on continuation.
ALTER TABLE rm.target_clarifications ADD COLUMN user_id uuid REFERENCES rm.local_users(id);
CREATE TRIGGER attribute_local_user BEFORE UPDATE ON rm.target_clarifications FOR EACH ROW
    WHEN (OLD.decided_at IS NULL AND NEW.decided_at IS NOT NULL)
    EXECUTE FUNCTION rm.attribute_local_user();

ALTER TABLE rm.research_plans ADD COLUMN cancelled_user_id uuid REFERENCES rm.local_users(id);
CREATE TRIGGER attribute_plan_cancellation BEFORE UPDATE ON rm.research_plans FOR EACH ROW
    WHEN (OLD.cancelled_at IS NULL AND NEW.cancelled_at IS NOT NULL)
    EXECUTE FUNCTION rm.attribute_local_user('cancellation');
